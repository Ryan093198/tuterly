// Resolve a year level + subject list to the right curriculum block.
//
// `subject` discriminates between curriculum frameworks: 'maths' (default,
// for back-compat with rows that predate the column) or 'english'. The
// existing `subjects` array is only consulted for VCE Maths study designs.
// Old subject strings that pre-date the Units 1-2 / Units 3-4 split.
// Stored on existing students.subjects[] arrays — resolve to the new key
// transparently so we don't have to migrate user data.
const VCE_MATHS_ALIASES = {
  "VCE General Maths": "VCE General Maths Units 3-4",
};

function vceMathsKey(s) {
  if (!s) return s;
  return VCE_MATHS_ALIASES[s] ?? s;
}

export function getCurriculumForStudent(yearLevel, subjects, subject = "maths") {
  const normalised = yearLevel?.replace(/\s+/g, " ").trim();

  if (subject === "english") {
    if (normalised && VCAA_ENGLISH[normalised]) {
      return {
        level: normalised,
        curriculum: VCAA_ENGLISH[normalised],
        isVCE: false,
        subject: "english",
      };
    }
    if (
      normalised &&
      /^foundation|prep|reception$/i.test(normalised) &&
      VCAA_ENGLISH["Foundation"]
    ) {
      return {
        level: "Foundation",
        curriculum: VCAA_ENGLISH["Foundation"],
        isVCE: false,
        subject: "english",
      };
    }
    const num = normalised?.match(/(\d+)/)?.[1];
    if (num) {
      const key = `Level ${num}`;
      if (VCAA_ENGLISH[key]) {
        return {
          level: key,
          curriculum: VCAA_ENGLISH[key],
          isVCE: false,
          subject: "english",
        };
      }
    }
    return null;
  }

  // Maths (default)
  if (subjects && subjects.length > 0) {
    for (const subj of subjects) {
      const key = vceMathsKey(subj);
      if (VCE_MATHS[key]) {
        return {
          level: key,
          curriculum: VCE_MATHS[key],
          isVCE: true,
          subject: "maths",
        };
      }
    }
  }

  const normalisedVceKey = vceMathsKey(normalised);
  if (normalisedVceKey && VCE_MATHS[normalisedVceKey]) {
    return {
      level: normalisedVceKey,
      curriculum: VCE_MATHS[normalisedVceKey],
      isVCE: true,
      subject: "maths",
    };
  }

  if (normalised && VCAA_MATHS[normalised]) {
    return {
      level: normalised,
      curriculum: VCAA_MATHS[normalised],
      isVCE: false,
      subject: "maths",
    };
  }

  const num = normalised?.match(/(\d+)/)?.[1];
  if (num) {
    const key = `Year ${num}`;
    if (VCAA_MATHS[key]) {
      return {
        level: key,
        curriculum: VCAA_MATHS[key],
        isVCE: false,
        subject: "maths",
      };
    }
  }
  return null;
}

export function formatCurriculumForPrompt(curriculum, isVCE) {
  if (!curriculum) return "";
  let output = "";
  for (const [strand, items] of Object.entries(curriculum)) {
    output += `\n### ${strand}\n`;
    for (const item of items) {
      output += isVCE
        ? `- ${item.topic}: ${item.desc}\n`
        : `- ${item.code}: ${item.desc}\n`;
    }
  }
  return output;
}
